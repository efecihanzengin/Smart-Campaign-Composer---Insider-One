-- A running generation call blocks approval of its Campaign. Each call has
-- its own row, which it renews while it runs and deletes when it ends; a row
-- past expires_at was left by an api process that died mid-call and no longer
-- blocks. This replaces generation_started_at and its fixed staleness window,
-- which blocked approval for minutes after a crash and let it through during
-- a call that outlasted the window.
ALTER TABLE campaigns DROP COLUMN generation_started_at;

CREATE TABLE generations (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id bigint      NOT NULL REFERENCES campaigns (id) ON DELETE CASCADE,
    expires_at  timestamptz NOT NULL
);

CREATE INDEX generations_campaign ON generations (campaign_id, expires_at);

-- A Delivery of a cancelled Campaign that was never handed to the Provider
-- ends `cancelled` (ADR-0006), so the final counts show what was sent,
-- failed and cancelled instead of leaving it `pending` forever.
ALTER TABLE deliveries DROP CONSTRAINT deliveries_state_check,
    ADD CONSTRAINT deliveries_state_check CHECK (state IN ('pending', 'sending', 'sent', 'failed', 'cancelled'));

-- A Delivery's outcome is unknown once one of its Attempts got no answer
-- (timeout, connection error, worker shutdown): the Provider may have
-- accepted it. Under a cancelled Campaign such a Delivery is retried with the
-- same Idempotency-Key until the Provider says what happened, instead of
-- being cancelled while it may have been sent.
CREATE FUNCTION delivery_outcome_unknown(delivery bigint) RETURNS boolean
    LANGUAGE sql STABLE
    RETURN EXISTS (SELECT 1 FROM attempts a WHERE a.delivery_id = delivery AND a.status_code IS NULL);

-- cancel_unsent_deliveries moves every `pending` Delivery of a cancelled
-- Campaign whose outcome is known to `cancelled`, and returns how many. Rows
-- a worker is claiming right now are skipped, not waited for: the next call
-- picks them up. The api calls it on cancel and every worker poll calls it.
CREATE FUNCTION cancel_unsent_deliveries() RETURNS bigint
    LANGUAGE sql
    AS $$
        WITH unsent AS (
            SELECT d.id FROM deliveries d
            JOIN campaigns c ON c.id = d.campaign_id
            WHERE c.status = 'cancelled' AND d.state = 'pending' AND NOT delivery_outcome_unknown(d.id)
            FOR UPDATE OF d SKIP LOCKED
        ), done AS (
            UPDATE deliveries d SET state = 'cancelled', updated_at = now()
            FROM unsent WHERE d.id = unsent.id AND d.state = 'pending'
            RETURNING 1
        )
        SELECT count(*) FROM done
    $$;
